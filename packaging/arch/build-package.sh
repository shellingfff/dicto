#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/../.."
repo_root=$PWD
version=$(sed -n 's/^version = "\([^"]*\)"/\1/p' desktop/Cargo.toml)
config_version=$(sed -n 's/.*"version": "\([^"]*\)".*/\1/p' desktop/tauri.conf.json)
if [[ ! $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ || $version != "$config_version" ]]; then
    echo 'Arch packaging requires matching numeric application versions.' >&2
    exit 1
fi

output="$repo_root/target/arch-package"
mkdir -p "$output"
archive="dicto-$version.tar.gz"
tar --exclude=desktop/gen --exclude=desktop/permissions/autogenerated \
    --transform="s,^,dicto-$version/," -czf "$output/$archive" \
    Cargo.toml Cargo.lock Makefile LICENSE src desktop frontend assets packaging/linux
checksum=$(sha256sum "$output/$archive")
checksum=${checksum%% *}
sed -e "s/@VERSION@/$version/g" -e "s/@SHA256@/$checksum/g" \
    packaging/arch/PKGBUILD.in > "$output/PKGBUILD"
cd "$output"
makepkg --cleanbuild --force "$@"
